/**
 * Planner Agent (Aria) — explores the application and generates test plans.
 *
 * Discovers interactive elements on the target page and writes structured
 * Markdown test plans to the specs/ directory.
 */

import * as cheerio from "cheerio";
import * as fs from "node:fs";
import * as path from "node:path";

interface DiscoveredElement {
  type: string;
  name: string;
  placeholder: string;
  required: boolean;
}

interface DiscoveredButton {
  text: string;
  type: string;
}

interface PageElements {
  url: string;
  title: string;
  inputs: DiscoveredElement[];
  buttons: DiscoveredButton[];
  links: { text: string; href: string }[];
}

/** Fetch a page and extract interactive elements using cheerio. */
export async function discoverElements(url: string): Promise<PageElements> {
  const response = await fetch(url, {
    headers: { "User-Agent": "AgenticTestPlanner/1.0" },
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status} fetching ${url}`);
  }

  const html = await response.text();
  const $ = cheerio.load(html);

  const elements: PageElements = {
    url,
    title: $("title").text().trim() || "",
    inputs: [],
    buttons: [],
    links: [],
  };

  $("input").each((_, el) => {
    const type = $(el).attr("type") || "text";
    if (type === "hidden" || type === "submit") return;
    elements.inputs.push({
      type,
      name: $(el).attr("name") || $(el).attr("id") || "",
      placeholder: $(el).attr("placeholder") || "",
      required: $(el).attr("required") !== undefined,
    });
  });

  $("button").each((_, el) => {
    elements.buttons.push({
      text: $(el).text().trim(),
      type: $(el).attr("type") || "button",
    });
  });

  return elements;
}

/** Fallback template for saucedemo.com when the fetch fails. */
export function templateElements(url: string): PageElements {
  return {
    url,
    title: "Swag Labs",
    inputs: [
      { type: "text", name: "user-name", placeholder: "Username", required: true },
      { type: "password", name: "password", placeholder: "Password", required: true },
    ],
    buttons: [{ text: "Login", type: "submit" }],
    links: [],
  };
}

/** Generate a structured Markdown test plan from discovered elements. */
export function generateTestPlan(
  elements: PageElements,
  seed: string,
  appName: string
): string {
  const pageName = elements.title.toLowerCase().replace(/\s+/g, "-").slice(0, 40);
  const lines: string[] = [];

  lines.push(`# Test Plan: ${appName} — ${pageName}`);
  lines.push("");
  lines.push(`> Generated by Planner Agent (Aria) on ${new Date().toISOString()}`);
  lines.push("> Target: " + elements.url);
  lines.push("> Seed: " + seed);
  lines.push("");

  lines.push("## Page Object");
  lines.push("");
  lines.push("```yaml");
  lines.push("page_name: " + pageName);
  lines.push("url: " + elements.url);
  lines.push("elements:");
  for (const inp of elements.inputs) {
    lines.push(`  - type: ${inp.type}`);
    lines.push(`    selector: [data-test='${inp.name}']`);
    lines.push(`    fallback: '#${inp.name}'`);
    lines.push(`    placeholder: ${inp.placeholder}`);
  }
  for (const btn of elements.buttons) {
    lines.push("  - type: button");
    lines.push(`    text: ${btn.text}`);
  }
  lines.push("```");
  lines.push("");

  lines.push("## Test Cases");
  lines.push("");

  const hasPassword = elements.inputs.some((i) => i.type === "password");
  if (hasPassword) {
    lines.push("### TC-001: Successful login");
    lines.push("- **Precondition**: User is on the login page");
    lines.push("- **Steps**:");
    for (const inp of elements.inputs) {
      if (inp.type === "password") lines.push(`  1. Enter valid password in \`${inp.name}\``);
      else lines.push(`  1. Enter \`standard_user\` in \`${inp.name}\``);
    }
    lines.push("  1. Click the submit button");
    lines.push("- **Expected**: User is redirected to the inventory page");
    lines.push("");

    lines.push("### TC-002: Login with invalid credentials");
    lines.push("- **Steps**: Enter invalid_user + wrong_password, click submit");
    lines.push("- **Expected**: Error message displayed");
    lines.push("");

    lines.push("### TC-003: Login with empty fields");
    lines.push("- **Steps**: Click submit without entering data");
    lines.push("- **Expected**: Validation error displayed");
    lines.push("");
  }

  if (seed.includes("inventory") || seed.includes("browse")) {
    lines.push("### TC-010: Browse inventory after login");
    lines.push("- **Precondition**: User is logged in");
    lines.push("- **Steps**: Verify items, sort by name, verify sorting");
    lines.push("- **Expected**: Items sorted correctly");
    lines.push("");
  }

  lines.push("## Assertions");
  lines.push("");
  lines.push("```typescript");
  lines.push('await expect(page).toHaveURL(/.*inventory.*/);');
  lines.push('await expect(page.locator(\'[data-test="title\"]\')).toContainText("Products");');
  lines.push("```");
  lines.push("");

  return lines.join("\n");
}

/** Main entry point for the Planner agent. */
export async function runPlanner(url: string, seed: string, outputDir: string, appName: string): Promise<string> {
  let elements: PageElements;
  try {
    elements = await discoverElements(url);
  } catch {
    elements = templateElements(url);
  }

  const plan = generateTestPlan(elements, seed, appName);
  const pageName = elements.title.toLowerCase().replace(/\s+/g, "-").slice(0, 40) || "page";

  fs.mkdirSync(outputDir, { recursive: true });
  const specFile = path.join(outputDir, `${pageName}.md`);
  fs.writeFileSync(specFile, plan, "utf-8");

  console.log(`[Planner] Test plan written to ${specFile}`);
  return specFile;
}